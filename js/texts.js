export function mbtiHeadline(score) {
  if (score >= 80) return '말이 척척 통하는 사이';
  if (score >= 60) return '편안하게 잘 맞는 사이';
  if (score >= 40) return '맞춰 갈수록 좋아지는 사이';
  return '다름이 매력인 사이';
}

// 닉네임 뒤 조사를 받침에 맞게 고른다. [받침 없을 때, 받침 있을 때]
const JOSA = [['는', '은'], ['가', '이'], ['를', '을'], ['와', '과'], ['야', '아']];
const JOSA_RE = new RegExp(`\\{([AB])\\}(${JOSA.flat().join('|')})?(?=[\\s,.!?·)]|$)`, 'g');

function hasBatchim(word) {
  const code = word.charCodeAt(word.length - 1) - 0xAC00;
  return code >= 0 && code <= 11171 && code % 28 !== 0;
}

/** {A}, {B}를 실제 닉네임으로 */
export function fillNames(text, nameA, nameB) {
  return text
    .replace(JOSA_RE, (_, who, josa) => {
      const name = who === 'A' ? nameA : nameB;
      if (!josa) return name;
      const pair = JOSA.find((p) => p.includes(josa));
      return name + pair[hasBatchim(name) ? 1 : 0];
    })
    .replaceAll('{A}', nameA)
    .replaceAll('{B}', nameB);
}
