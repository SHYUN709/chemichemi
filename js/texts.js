/** 사주 관계 해설 ({A}/{B} 자리표시자 포함) */
export function sajuText(rel, stemA, stemB) {
  if (rel.type === 'hap') {
    const [lo, hi] = [stemA, stemB].sort((x, y) => x.index - y.index);
    return HAP[lo.hanja + hi.hanja];
  }
  if (rel.type === 'bihwa') return BIHWA[stemA.element];
  const giver = rel.from === 'a' ? stemA : stemB;
  const table = rel.type === 'saeng' ? SAENG : GEUK;
  const [g, r] = rel.from === 'a' ? ['{A}', '{B}'] : ['{B}', '{A}'];
  return table[giver.element].replaceAll('{G}', g).replaceAll('{R}', r);
}

